# Figures the extractor does not list: French thousands separator and decimal comma.
NUMBERS = {
    "15,000+": f"15{NB}000+", "20,000+": f"20{NB}000+", "40%": f"40{NB}%", "5th": "5e",
    "55.8M": "55,8 M", "16M": "16 M", "1.57B": "1,57 Md",
}
for n in ["3,200,000", "1,450,000", "820,000", "610,000", "455,000", "380,000", "290,000", "645,000",
          "61,000", "48,500", "39,200", "27,800", "22,100", "51,400", "250,000",
          "2,100", "1,650", "1,240", "2,700", "9,400"]:
    NUMBERS[n] = n.replace(",", NB)

keys = list(json.load(open("strings.json", encoding="utf8")))
out, errors = {}, []
for en, fr in FR:
    hits = [en] if en in keys else [k for k in keys if k.startswith(en)]
    if len(hits) != 1:
        errors.append(f"{en!r}: {len(hits)} matches")
        continue
    out[hits[0]] = fr
out.update(NUMBERS)
for k in keys:
    out.setdefault(k, "")
if errors:
    print("\n".join(errors)); sys.exit(1)
json.dump(out, open("fr.json", "w", encoding="utf8"), indent=1, ensure_ascii=False)
hy = [v for v in out.values() if "-" in v or "–" in v or "—" in v]
print(f"fr.json: {sum(1 for v in out.values() if v)} translated, {sum(1 for v in out.values() if not v)} kept as is")
if hy: print("dashes found:", hy)
